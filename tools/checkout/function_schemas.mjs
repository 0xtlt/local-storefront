#!/usr/bin/env node
// Writes the Function API schemas of lsf-checkout (crates/checkout/schemas/<version>/<api>.graphql).
//
// Source: the npm package @shopify/dev-mcp (ISC, Shopify), pinned below. It ships the
// introspection of every Function API for each API release; no login is needed (`shopify app
// function schema` needs one). The tarball is checked against the pinned SHA-256, so the
// result is reproducible. Needs network access and `npm`.
//
// To add a version: add it to VERSIONS, pin a @shopify/dev-mcp release that has it, run
// `mise run checkout:schemas`, then add the version to crates/checkout/src/version.rs.
//
// The introspection carries no `@oneOf`, which the Rust Function typegen needs to turn an
// operation into an enum: an input object whose fields are all optional is a `@oneOf`, but for
// NOT_ONE_OF (checked against Shopify's examples and the docs).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";

const PACKAGE = "@shopify/dev-mcp@1.17.0";
const SHA256 = "f651c221109dbc55601ab7a85353f3b82fec8ec9bbf9f260440139e28c7e8a7a";

const VERSIONS = ["2026-10", "2027-01"];
// The file name in the package -> the name in lsf-checkout (`FunctionApi`).
const APIS = {
  cart_checkout_validation: "cart_checkout_validation",
  cart_transform: "cart_transform",
  delivery_customization: "delivery_customization",
  discount: "discount",
  order_discounts: "order_discount",
  payment_customization: "payment_customization",
  product_discounts: "product_discount",
  shipping_discounts: "shipping_discount",
};

// Optional-only input objects that are plain objects, not `@oneOf`.
const NOT_ONE_OF = new Set([
  "PaymentTermsSetOperation", // `paymentTermsSet: {}` removes the payment terms
  "PriceAdjustment",
  "ProductDiscountCandidatePrerequisite",
]);
const isFetchResult = (name) => name.endsWith("FetchResult");

const PLACEHOLDER = "_noField"; // also in crates/checkout/src/schema.rs

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "crates/checkout/schemas");

const work = mkdtempSync(join(tmpdir(), "lsf-function-schemas-"));
try {
  execFileSync("npm", ["pack", PACKAGE, "--silent", "--pack-destination", work], {
    stdio: ["ignore", "ignore", "inherit"],
  });
  const tarball = join(work, readdirSingle(work));
  const sha = createHash("sha256").update(readFileSync(tarball)).digest("hex");
  if (sha !== SHA256) throw new Error(`${PACKAGE}: SHA-256 is ${sha}, expected ${SHA256}`);
  const unpacked = join(work, "unpacked");
  mkdirSync(unpacked);
  execFileSync("tar", ["xzf", tarball, "-C", unpacked]);

  for (const version of VERSIONS) {
    mkdirSync(join(out, version), { recursive: true });
    for (const [file, api] of Object.entries(APIS)) {
      const path = join(unpacked, "package/dist/data", `functions_${file}_${version}.json.gz`);
      const schema = JSON.parse(gunzipSync(readFileSync(path))).data.__schema;
      writeFileSync(join(out, version, `${api}.graphql`), print(schema, version, file));
    }
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

function readdirSingle(dir) {
  const names = execFileSync("ls", [dir]).toString().trim().split("\n");
  if (names.length !== 1) throw new Error(`expected one tarball in ${dir}, got ${names}`);
  return names[0];
}

function typeRef(type) {
  if (type.kind === "NON_NULL") return `${typeRef(type.ofType)}!`;
  if (type.kind === "LIST") return `[${typeRef(type.ofType)}]`;
  return type.name;
}

function deprecated(item) {
  return item.isDeprecated
    ? ` @deprecated(reason: ${JSON.stringify(item.deprecationReason ?? "No longer supported")})`
    : "";
}

function args(field) {
  if (!field.args?.length) return "";
  return `(${field.args.map(input).join(", ")})`;
}

function input(item) {
  const fallback = item.defaultValue == null ? "" : ` = ${item.defaultValue}`;
  return `${item.name}: ${typeRef(item.type)}${fallback}${deprecated(item)}`;
}

function oneOf(type) {
  return (
    type.inputFields.length > 0 &&
    type.inputFields.every((field) => field.type.kind !== "NON_NULL" && field.defaultValue == null) &&
    !NOT_ONE_OF.has(type.name) &&
    !isFetchResult(type.name)
  );
}

function print(schema, version, file) {
  const builtin = new Set(["Boolean", "Float", "Int", "String", "ID"]);
  const lines = [
    `# Shopify Function API schema: ${file}, API version ${version}.`,
    `# Generated by tools/checkout/function_schemas.mjs from ${PACKAGE}: do not edit.`,
    "",
    "schema {",
    `  query: ${schema.queryType.name}`,
    ...(schema.mutationType ? [`  mutation: ${schema.mutationType.name}`] : []),
    "}",
    "",
  ];
  for (const directive of schema.directives) {
    if (["deprecated", "include", "skip", "specifiedBy"].includes(directive.name)) continue;
    const parameters = directive.args.length ? `(${directive.args.map(input).join(", ")})` : "";
    lines.push(`directive @${directive.name}${parameters} on ${directive.locations.join(" | ")}`, "");
  }
  const types = schema.types
    .filter((type) => !type.name.startsWith("__") && !builtin.has(type.name))
    .sort((a, b) => a.name.localeCompare(b.name));
  for (const type of types) {
    switch (type.kind) {
      case "SCALAR":
        lines.push(`scalar ${type.name}`);
        break;
      case "ENUM":
        lines.push(`enum ${type.name} {`);
        for (const value of type.enumValues) lines.push(`  ${value.name}${deprecated(value)}`);
        lines.push("}");
        break;
      case "UNION":
        lines.push(`union ${type.name} = ${type.possibleTypes.map((t) => t.name).join(" | ")}`);
        break;
      case "INTERFACE":
      case "OBJECT": {
        const keyword = type.kind === "OBJECT" ? "type" : "interface";
        const implemented = type.interfaces?.length
          ? ` implements ${type.interfaces.map((t) => t.name).join(" & ")}`
          : "";
        lines.push(`${keyword} ${type.name}${implemented} {`);
        for (const field of type.fields) {
          lines.push(`  ${field.name}${args(field)}: ${typeRef(field.type)}${deprecated(field)}`);
        }
        lines.push("}");
        break;
      }
      case "INPUT_OBJECT":
        lines.push(`input ${type.name}${oneOf(type) ? " @oneOf" : ""} {`);
        for (const field of type.inputFields) lines.push(`  ${input(field)}`);
        // SDL has no input object without a field. Shopify empties the legacy operations it no
        // longer takes (`DeprecatedOperation` of the delivery customization API): the
        // placeholder keeps the schema valid, lsf-checkout ignores it.
        if (type.inputFields.length === 0) lines.push(`  ${PLACEHOLDER}: Void`);
        lines.push("}");
        break;
      default:
        throw new Error(`${type.name}: unexpected kind ${type.kind}`);
    }
    lines.push("");
  }
  return `${lines.join("\n")}`;
}

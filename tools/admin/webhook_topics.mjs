#!/usr/bin/env node
// Writes the webhook topics of lsf-admin (crates/admin/src/webhooks/topics_2026_10.rs): every
// value of the `WebhookSubscriptionTopic` enum of the Admin API 2026-10, with the topic as
// Shopify writes it (`ORDERS_CREATE` is `orders/create`, `CUSTOMER_TAGS_ADDED` is
// `customer.tags_added`), the access scopes it requires and what it reports.
//
// The written form is not derived from the enum value: the split between the resource and the
// action is not mechanical (`CUSTOMERS_EMAIL_MARKETING_CONSENT_UPDATE` is
// `customers_email_marketing_consent/update`). It is read from the description of each value,
// which starts with "The webhook topic for `<topic>` events."; the run fails when one does not.
//
// Source: the npm package @shopify/dev-mcp (ISC, Shopify), pinned below, which ships the
// introspection of the Admin API of each release with its descriptions. The tarball is checked
// against the pinned SHA-256, so the result is reproducible. Needs network access and `npm`.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";

const PACKAGE = "@shopify/dev-mcp@1.17.0";
const SHA256 = "f651c221109dbc55601ab7a85353f3b82fec8ec9bbf9f260440139e28c7e8a7a";
const VERSION = "2026-10";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "crates/admin/src/webhooks/topics_2026_10.rs");

const work = mkdtempSync(join(tmpdir(), "lsf-webhook-topics-"));
try {
  execFileSync("npm", ["pack", PACKAGE, "--silent", "--pack-destination", work], {
    stdio: ["ignore", "ignore", "inherit"],
  });
  const tarballs = readdirSync(work);
  if (tarballs.length !== 1) throw new Error(`expected one tarball in ${work}, got ${tarballs}`);
  const tarball = join(work, tarballs[0]);
  const sha = createHash("sha256").update(readFileSync(tarball)).digest("hex");
  if (sha !== SHA256) throw new Error(`${PACKAGE}: SHA-256 is ${sha}, expected ${SHA256}`);
  const unpacked = join(work, "unpacked");
  mkdirSync(unpacked);
  execFileSync("tar", ["xzf", tarball, "-C", unpacked]);

  const path = join(unpacked, "package/dist/data", `admin_${VERSION}.json.gz`);
  const schema = JSON.parse(gunzipSync(readFileSync(path))).data.__schema;
  const topicType = schema.types.find((type) => type.name === "WebhookSubscriptionTopic");
  const rows = topicType.enumValues.map((value) => {
    const description = (value.description ?? "").replace(/\s+/g, " ").trim();
    const written = /^The webhook topic for `([^`]+)` events\. ?/.exec(description);
    if (!written) throw new Error(`${value.name}: no topic in its description: ${description}`);
    const rest = description.slice(written[0].length);
    const scopes = [];
    const one = /Requires the `([a-z_]+)` scope\./.exec(rest);
    const any = /Requires at least one of the following scopes: ([a-z_, ]+)\./.exec(rest);
    if (one) scopes.push(one[1]);
    if (any) scopes.push(...any[1].split(",").map((scope) => scope.trim()));
    const summary = rest
      .replace(/ ?Requires the `[a-z_]+` scope\./, "")
      .replace(/ ?Requires at least one of the following scopes: [a-z_, ]+\./, "")
      .trim();
    return { name: value.name, written: written[1], scopes, summary, deprecated: value.isDeprecated };
  });

  const lines = [
    `//! The \`WebhookSubscriptionTopic\` enum of the Admin API ${VERSION}: ${rows.length} topics.`,
    `//! Generated by tools/admin/webhook_topics.mjs from ${PACKAGE}: do not edit.`,
    "",
    "use super::Topic;",
    "",
    "pub(super) const TOPICS: &[Topic] = &[",
  ];
  for (const row of rows) {
    lines.push(
      "    Topic {",
      `        name: ${JSON.stringify(row.name)},`,
      `        written: ${JSON.stringify(row.written)},`,
      `        scopes: &[${row.scopes.map((scope) => JSON.stringify(scope)).join(", ")}],`,
      `        summary: ${JSON.stringify(row.summary)},`,
      ...(row.deprecated ? ["        deprecated: true,"] : ["        deprecated: false,"]),
      "    },",
    );
  }
  lines.push("];", "");
  writeFileSync(out, lines.join("\n"));
  console.log(`${out}: ${rows.length} topics`);
} finally {
  rmSync(work, { recursive: true, force: true });
}

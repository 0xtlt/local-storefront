#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes crates/core/src/store/country_names.rs, the names of the countries Shopify lists in the
# languages lsf knows, from a checkout of Shopify/worldwide (https://github.com/Shopify/worldwide),
# the address data Shopify uses:
#
#   ruby tools/worldwide/country_names.rb path/to/worldwide
#
# A country is a region of `data/regions/` with a continent (`group_name`) that is not deprecated,
# but those Shopify sells to none of (EXCLUDED): 237 countries. Its name in a language is the one
# of `data/cldr/locales/<locale>/territories.yml`, as worldwide's `Region#full_name` gives it: the
# locale's own file, else its parent's in CLDR's chain (`nb` takes `no`'s, `pt-BR` `pt`'s).

require "yaml"

EXCLUDED = ["BV", "CU", "HM", "IR", "KP", "SY"].freeze

worldwide = ARGV.fetch(0) { abort("usage: ruby tools/worldwide/country_names.rb path/to/worldwide") }
commit = `git -C #{worldwide} rev-parse --short=7 HEAD`.strip
cldr = File.join(worldwide, "data/cldr")

reference = File.read(File.expand_path("../../crates/core/src/store/reference.rs", __dir__))
languages = reference[/^const LANGUAGES.*?^\];/m].scan(/^\s+\("([A-Za-z-]+)",/).flatten
abort("no LANGUAGES in reference.rs") if languages.empty?

codes = Dir[File.join(worldwide, "data/regions/*.yml")].filter_map do |path|
  region = YAML.load_file(path)
  code = region.fetch("code")
  code unless region["deprecated"] || region["group_name"].nil? || EXCLUDED.include?(code)
end.sort
abort("expected 237 countries, got #{codes.size}") unless codes.size == 237

parents = YAML.load_file(File.join(cldr, "parent_locales.yml"))

# The territories of each locale of CLDR's chain, from the locale to its language: a name a
# locale lacks is its parent's (`pt-PT` has only those it writes differently from `pt`).
chain = lambda do |locale|
  tables = []
  until locale == "root"
    path = File.join(cldr, "locales", locale, "territories.yml")
    tables << [locale, YAML.load_file(path).fetch(locale).fetch("territories")] if File.exist?(path)
    locale = parents.fetch(locale) { locale.include?("-") ? locale.sub(/-[^-]+\z/, "") : "root" }
  end
  abort("no territories for #{locale}") if tables.empty?
  tables
end

tables = languages.map do |language|
  sources = chain.call(language)
  names = codes.map do |code|
    sources.each { |_, territories| break territories[code] if territories.key?(code) } ||
      abort("no name for #{code} in #{language}")
  end
  [language, sources.first.first, names]
end

# A regional language whose names are those of its language is left to that one: `pt-BR` reads
# `pt`'s, which lsf falls back to.
tables.reject! do |language, _, names|
  base = language.split("-").first
  base != language && tables.any? { |other, _, other_names| other == base && other_names == names }
end

rust = +<<~RUST
  //! The names of the countries Shopify lists, in the languages lsf knows (`reference::LANGUAGES`),
  //! as Shopify gives them on a page in that language: `États-Unis` in French.
  //!
  //! Generated by `tools/worldwide/country_names.rb` from Shopify/worldwide
  //! (https://github.com/Shopify/worldwide, commit `#{commit}`), (c) Shopify Inc., MIT license (see
  //! `data/NOTICE.md`): the names of `data/cldr/locales/<locale>/territories.yml`, which derive from
  //! the Unicode CLDR. A regional language whose names are those of its language is left out.

  /// The countries, by code.
  pub(super) const CODES: [&str; #{codes.size}] = [
RUST
codes.each_slice(16) { |slice| rust << "    #{slice.map(&:inspect).join(", ")},\n" }
rust << <<~RUST
  ];

  /// `(language, names)`: the name of each country of [`CODES`], in its order, one per line.
  pub(super) const NAMES: &[(&str, &str)] = &[
RUST
tables.each do |language, source, names|
  abort("a name of #{language} has a line break") if names.any? { |name| name.include?("\n") }
  rust << "    // The names of `#{source}`.\n" unless source == language
  rust << "    (\n"
  rust << "        #{language.inspect},\n"
  rust << "        \"#{names.map { |name| name.gsub("\\", "\\\\\\\\").gsub('"', '\\"') }.join("\n")}\",\n"
  rust << "    ),\n"
end
rust << "];\n"

out = File.expand_path("../../crates/core/src/store/country_names.rs", __dir__)
File.write(out, rust)
warn "wrote #{out}: #{codes.size} countries in #{tables.size} languages"

#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes crates/core/src/store/countries.rs, the countries Shopify lists, from a checkout of
# Shopify/worldwide (https://github.com/Shopify/worldwide), the address data Shopify's checkout
# uses:
#
#   ruby tools/worldwide/countries.rb path/to/worldwide
#
# A country is a region of `data/regions/` with a `group_name`, the continent Liquid's
# `country.continent` gives, that is not deprecated. Its name is the English one of
# `data/cldr/locales/en/territories.yml`, as worldwide's `Region#full_name` gives it, its
# currency that of the region. Shopify sells to none of the countries of EXCLUDED: its address
# service lists 237 countries, worldwide's but those.

require "yaml"

EXCLUDED = {
  "BV" => "Bouvet Island",
  "CU" => "Cuba",
  "HM" => "Heard & McDonald Islands",
  "IR" => "Iran",
  "KP" => "North Korea",
  "SY" => "Syria",
}.freeze

worldwide = ARGV.fetch(0) { abort("usage: ruby tools/worldwide/countries.rb path/to/worldwide") }
commit = `git -C #{worldwide} rev-parse --short=7 HEAD`.strip
names = YAML.load_file(File.join(worldwide, "data/cldr/locales/en/territories.yml")).fetch("en").fetch("territories")

countries = Dir[File.join(worldwide, "data/regions/*.yml")].filter_map do |path|
  region = YAML.load_file(path)
  code = region.fetch("code")
  next if region["deprecated"] || region["group_name"].nil? || EXCLUDED.key?(code)

  [code, names.fetch(code), region.fetch("currency"), region.fetch("group_name")]
end.sort

abort("expected 237 countries, got #{countries.size}") unless countries.size == 237

rust = +<<~RUST
  //! The countries Shopify lists, as `(code, name, currency, continent)` sorted by code: the
  //! English name Shopify gives each, the currency it pays in and the continent Liquid's
  //! `country.continent` gives.
  //!
  //! Generated by `tools/worldwide/countries.rb` from Shopify/worldwide
  //! (https://github.com/Shopify/worldwide, commit `#{commit}`), (c) Shopify Inc., MIT license (see
  //! `data/NOTICE.md`): the regions of `data/regions/` with a continent (`group_name`), named by
  //! `data/cldr/locales/en/territories.yml`. Shopify sells to none of the others
  //! (#{EXCLUDED.keys.join(", ")}).

  /// A country: `(code, name, currency, continent)`.
  pub(super) type CountryData = (&'static str, &'static str, &'static str, &'static str);

  pub(super) const COUNTRIES: [CountryData; #{countries.size}] = [
RUST
countries.each do |code, name, currency, continent|
  rust << "    (#{code.inspect}, #{name.inspect}, #{currency.inspect}, #{continent.inspect}),\n"
end
rust << "];\n"

out = File.expand_path("../../crates/core/src/store/countries.rs", __dir__)
File.write(out, rust)
warn "wrote #{out}: #{countries.size} countries"
